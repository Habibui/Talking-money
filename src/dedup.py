"""
Программная (не-LLM) подстраховка от дублей между источниками.

Модель уже сама сверяет новую новость со списком recent_posts и возвращает
"story_status": "duplicate"/"update"/"new" (см. SYSTEM_PROMPT в llm.py) — это
основной механизм. Но 16.09.2026 обнаружилось (см. claude/pipeline-v1-setup.md,
инцидент 16.09.2026), что этот механизм пропускает дубли СИСТЕМАТИЧЕСКИ, а не
изредка — типичный случай: один источник (чаще всего агрегатор вроде
Investing.com) публикует несколько заметок об одном и том же событии с разницей
в секунды-минуты (решение + реакция рынка + прогноз), и каждая уходит с
story_status="new". Изначально (14-15.09.2026) этот модуль подстраховывал
только "breaking" (понижая до "routine" при срабатывании) — сочтено было, что
для "routine" риск ниже, дубль просто займёт лишнюю строчку в дайджесте. Но
16.09 выяснилось, что подавляющее большинство таких пропущенных дублей САМИ
изначально шли как "routine" — то есть та версия фильтра их вообще не
проверяла, и дайджест забивался копиями одной и той же истории.

Поэтому теперь это — второй, независимый от LLM слой, применяемый КО ВСЕМ
новым новостям (см. main.py), а не только к "breaking": простое текстовое
сходство между новым headline_ru+comment_ru и уже опубликованными/поставленными
в очередь за последние ~48ч. Это не замена смысловой проверки модели, а
подстраховка на случай, если она дубль не заметила — при срабатывании новость
обрабатывается ТОЧНО ТАК ЖЕ, как LLM-обнаруженный "duplicate": не публикуется и
не идёт в дайджест вовсе (раньше здесь было только мягкое понижение urgency —
этого хватало для редких промахов на "breaking", но не решало проблему
дублирования внутри "routine", которая и оказалась основной).
"""

import re

# Частые русские служебные слова + общеканальные шаблонные слова, которые
# встречаются почти в каждом посте независимо от конкретной истории и поэтому
# не несут различающего сигнала. Сознательно не трогаем цифры и потенциальные
# имена собственные (см. _tokenize) — именно они и отличают одну историю от
# другой, шаблонные же слова только "разбавляют" пересечение.
_STOPWORDS = {
    "и", "в", "на", "с", "по", "за", "от", "до", "при", "для", "из", "к", "о", "об",
    "не", "ни", "же", "ли", "бы", "то", "а", "но", "или", "как", "что", "это", "этот",
    "эта", "это", "эти", "тот", "та", "те", "все", "всё", "весь", "уже", "ещё", "еще",
    "снова", "опять", "теперь", "сейчас", "сегодня", "тут", "там", "здесь", "между",
    "среди", "около", "почти", "просто", "слишком", "очень", "самый", "самая", "самое",
    "самые", "может", "могут", "должен", "должна", "должны", "нужно", "надо", "стоит",
    "если", "чтобы", "только", "даже", "вроде", "типа", "скорее", "его", "её", "их",
    "он", "она", "они", "было", "будет", "есть", "быть", "своё", "свою", "свои", "свой",
    "который", "которая", "которое", "которые", "так", "также", "тоже", "вот", "чем",
    "чём", "кто", "куда", "когда", "почему", "зачем", "рынок", "рынка", "рынке",
    "рынки", "рынков", "рынком", "компания", "компании", "компанию", "компаний",
    "компанией", "новость", "новости", "деньги", "денег", "процент", "процента",
    "процентов", "процентный", "процентного", "миллиард", "миллиарда", "миллиардов",
    "миллион", "миллиона", "миллионов", "триллион", "триллиона", "триллионов",
}

_WORD_RE = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)


def _stem_key(low_word: str, has_digit: bool) -> str:
    """Грубый заменитель нормальной морфологии (без внешних библиотек и
    словарей): русский язык сильно склоняется по падежам ("Ормузский пролив" /
    "в Ормузском проливе" / "Ормузского пролива"), и при сравнении ДВУХ
    независимо сгенерированных моделью формулировок одного и того же факта
    точное совпадение целых слов — редкость, даже если по сути это одно и то
    же слово. Обрезка длинных слов до первых 5 символов покрывает большинство
    падежных окончаний (обычно 1-3 символа) и худо-бедно сводит разные формы
    одного слова к общему ключу, не собирая словарь и не подключая внешние
    NLP-библиотеки. Цифры не усекаем — это исказило бы само число."""
    if has_digit or len(low_word) <= 5:
        return low_word
    return low_word[:5]


# Позиция начала предложения СЕРЕДИНЕ текста (сразу после ".", "!", "?", "—" с
# пробелом) — слово там пишется с большой буквы просто по правилам пунктуации,
# не как сигнал имени собственного (иначе "Нефть тут же отреагировала..." в
# комментарии ложно засчитывается как "значимая" сущность наравне с реальными
# именами). Самое первое слово всей строки (headline_ru — она всегда идёт
# первой в склеенном тексте, см. is_near_duplicate) НЕ считается началом
# предложения в этом смысле: заголовки в этом канале почти всегда начинаются
# с самого субъекта новости ("ФРС снизила...", "Nvidia отчиталась...") — это
# как раз самый частый случай настоящей значимой сущности, и его нельзя
# терять наравне со случайным словом в начале произвольного предложения.
_SENTENCE_START_RE = re.compile(r"[.!?—]\s+\s*([A-Za-zА-Яа-яЁё])")


def _sentence_start_positions(text: str) -> set:
    return {m.start(1) for m in _SENTENCE_START_RE.finditer(text)}


def _tokenize(text: str) -> tuple[set, set]:
    """Возвращает (content_tokens, salient_tokens) — второе - это подмножество
    первого: числа (сильный сигнал "та же история") и слова, написанные с
    большой буквы НЕ в начале предложения (грубая эвристика на имена
    собственные — тикеры, компании, страны, персоны), длиной от 3 символов.
    Токены — не сами слова, а их огрублённые "ключи" через _stem_key (см. её
    докстринг)."""
    content: set = set()
    salient: set = set()
    sentence_starts = _sentence_start_positions(text)
    for m in re.finditer(r"[A-Za-zА-Яа-яЁё0-9]+", text):
        raw_word = m.group(0)
        low = raw_word.lower()
        has_digit = any(c.isdigit() for c in raw_word)
        is_capitalized = (
            raw_word[0].isupper()
            and len(raw_word) >= 3
            and not has_digit
            and m.start() not in sentence_starts
        )
        if not has_digit and not is_capitalized and low in _STOPWORDS:
            continue
        if len(low) < 2:
            continue
        key = _stem_key(low, has_digit)
        content.add(key)
        if has_digit or is_capitalized:
            salient.add(key)
    return content, salient


def _pair_score(text_a: str, text_b: str) -> tuple[float, int]:
    tokens_a, salient_a = _tokenize(text_a)
    tokens_b, salient_b = _tokenize(text_b)
    if not tokens_a or not tokens_b:
        return 0.0, 0
    union = tokens_a | tokens_b
    intersection = tokens_a & tokens_b
    jaccard = len(intersection) / len(union) if union else 0.0
    salient_overlap = len(salient_a & salient_b)
    return jaccard, salient_overlap


# Пороги подобраны на синтетических, но реалистичных примерах (см.
# scripts/tune_dedup.py) — цель: ловить явные пересказы одной и той же
# истории с других источников (общие числа/факты при разной стилистике
# перевода), но не путать с разными историями, у которых просто похожая
# шаблонная подача (например, "X отчиталась о рекордной выручке" для двух
# разных компаний). Три независимых условия (любое достаточно):
#   1) высокое общее пересечение слов само по себе (жёсткий порог, не требует
#      цифр/имён — на случай почти дословного повтора формулировок);
#   2) заметное пересечение + хотя бы один общий "значимый" токен
#      (число/имя собственное) — это и есть типичный случай одной и той же
#      истории, изложенной чуть разными словами;
#   3) два и более общих значимых токена — сильный сигнал сам по себе, даже
#      если остальная формулировка разошлась почти полностью.
JACCARD_HIGH = 0.55
JACCARD_MED = 0.30
SALIENT_MANY = 2


def is_near_duplicate(headline_ru: str, comment_ru: str, recent_posts: list) -> tuple[bool, float, dict | None]:
    """Сравнивает новый headline_ru+comment_ru с каждым recent_posts (список
    dict с ключами source/headline_ru/comment_ru — см. state.load_recent_posts).
    Возвращает (сработал_ли_фильтр, лучший_jaccard, лучший_совпавший_пост)."""
    if not recent_posts:
        return False, 0.0, None

    new_text = f"{headline_ru} {comment_ru}"
    best_jaccard = 0.0
    best_match = None
    best_trigger_jaccard = -1.0
    best_trigger_match = None

    for post in recent_posts:
        old_text = f"{post.get('headline_ru', '')} {post.get('comment_ru', '')}"
        jaccard, salient_overlap = _pair_score(new_text, old_text)

        if jaccard > best_jaccard:
            best_jaccard = jaccard
            best_match = post

        is_trigger = (
            jaccard >= JACCARD_HIGH
            or (jaccard >= JACCARD_MED and salient_overlap >= 1)
            or salient_overlap >= SALIENT_MANY
        )
        if is_trigger and jaccard > best_trigger_jaccard:
            best_trigger_jaccard = jaccard
            best_trigger_match = post

    if best_trigger_match is not None:
        return True, best_trigger_jaccard, best_trigger_match
    return False, best_jaccard, best_match
