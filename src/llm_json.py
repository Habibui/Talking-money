"""
Общая обвязка для всех четырёх ролей v2 (Экстрактор/Отборщик/Аналитик/
Фактчекер): разбор JSON-ответа + повтор при сбое формата. Раньше этот код
был скопирован в каждый из четырёх файлов (`extractor.py`/`selector.py`/
`analyst.py`/`factchecker.py`) по отдельности — вынесено сюда 26.09.2026 по
факту первого реального DRY_RUN на живых данных, который сразу нашёл
конкретный баг во всех четырёх копиях сразу: `max_tokens` был подобран "на
глаз", без реального прогона, и оказался мал для части ответов — 9 из 90
заметок в первом же прогоне сломались с `Unterminated string`/`Expecting
value` (классический признак того, что ответ модели ОБРЫВАЕТСЯ по лимиту
`max_tokens` до того, как JSON успевает закрыться, а не что модель
сгенерировала кривой JSON по своей воле). Все 9 сломанных заметок — с
русскоязычных источников (ЦБ РФ, Ведомости): вероятная причина — кириллица
у большинства токенизаторов "весит" больше на символ, чем латиница, то есть
то же по сути содержание `key_facts` на русском требует больше токенов, чем
на английском, а старый лимит был один для всех языков. У Отборщика (37
заметок разом, вход и так большой) отдельный сбой той же природы —
`Expecting value: line 1 column 1 (char 0)` — это ответ, обрубленный
настолько рано, что текстового блока в ответе не набралось вообще (весь
токен-бюджет ушёл до появления итогового текста).

**Решение — не бесконечно урезать вход (как для содержательных сбоев в
`llm.py` v1), а дать модели больше места на ВЫХОД при повторе**: это другая
по природе проблема, чем в v1 (там текст статьи мог обрываться посреди
цитаты на входе — здесь наоборот, ответ модели обрывается по лимиту на
выходе). `call_json_role()` принимает список `max_tokens_attempts` по
возрастанию — при сбое формата (`JSONDecodeError`/`ValueError`) повторяет
ТОТ ЖЕ запрос с бОльшим `max_tokens`, логируя `stop_reason` ответа для
диагностики (`"max_tokens"` в `stop_reason` — прямое подтверждение именно
этой причины, а не кривого JSON по другой причине). Стоимость это не
увеличивает для нормально отрабатывающих ответов — `max_tokens` это
потолок, а не то, что реально оплачивается; больше платится только за
реально сгенерированные токены, а повтор случается только при сбое.

**Второй реальный сбой, найденный уже ВТОРЫМ прогоном (26.09.2026, после
фикса выше) — сам этот фикс упёрся в отдельный, не связанный с JSON,
таймаут.** У Отборщика (38 заметок на входе) первая попытка
(`max_tokens=3000`) корректно обрубилась по лимиту, наш повтор сработал и
запросил `max_tokens=6000` — но САМ запрос второй попытки не успел
уложиться в таймаут HTTP-клиента (там было захардкожено фиксированное
значение вроде `timeout=60.0` при создании `anthropic.Anthropic(...)` в
каждой роли, одно и то же и для маленького, и для большого `max_tokens`).
SDK сам сделал свои внутренние повторы (видно в логах как "Retrying
request... in 0.5s / 0.9s"), но с тем же слишком коротким таймаутом каждый
из них был обречён повторить тот же тайм-аут — итог: `APITimeoutError`
("Request timed out"), который в `call_json_role()` ловится общим
`except Exception` и НЕ повторяется (сетевые ошибки — забота SDK, не
нашего цикла по `max_tokens_attempts`, см. комментарий там же) — то есть
раньше, чем наш собственный повтор с бОльшим `max_tokens` вообще получал
шанс. Генерация большого `max_tokens` объективно занимает больше времени,
а таймаут был один и тот же для всех попыток, а не привязан к тому, сколько
токенов реально запрошено.

**Фикс** — таймаут запроса больше не фиксированный на уровне клиента, а
вычисляется отдельно для КАЖДОЙ попытки, пропорционально её собственному
`max_tokens`, и передаётся явно в `client.messages.create(timeout=...)`
(SDK anthropic это поддерживает per-request, независимо от таймаута,
заданного при создании клиента — проверено сигнатурой метода). Формула в
`_request_timeout()` ниже — грубая, намеренно с запасом (консервативная
оценка скорости генерации + отдельный запас на обработку входа), не точный
расчёт: цель не "впритык", а "заведомо не упереться в тот же баг ещё раз"."""

import json
import logging

logger = logging.getLogger(__name__)


def _request_timeout(max_tokens: int) -> float:
    """Таймаут запроса, привязанный к запрошенному max_tokens этой конкретной
    попытки — не единое фиксированное значение на всех (см. docstring модуля
    про сбой 26.09.2026, когда одинаковый таймаут для маленькой и большой
    попытки убивал именно большую). Грубая консервативная оценка: ~30
    токенов/сек генерации + 30 сек запаса на обработку входа/сеть, но не
    меньше 60 сек даже для маленьких max_tokens (запас на холодный старт
    соединения). Оценка скорости не откалибрована точно по этой модели —
    цель дать заведомый запас, а не минимально достаточное значение."""
    return max(60.0, max_tokens / 30 + 30)


def strip_json_fences(raw: str) -> str:
    """Модель иногда оборачивает JSON в ```json ... ``` — снимаем разметку,
    если она есть; если её нет, строка возвращается как есть."""
    raw = raw.strip()
    if raw.startswith("```"):
        raw = raw.strip("`")
        raw = raw.split("\n", 1)[1] if "\n" in raw else raw
        if raw.lower().startswith("json"):
            raw = raw[4:]
    return raw.strip()


def call_json_role(
    client,
    model: str,
    system_prompt: str,
    user_content: str,
    max_tokens_attempts: list[int],
    role_name: str,
    log_ctx: str = "",
) -> dict | None:
    """Вызывает модель с указанным промптом, разбирает JSON-ответ (терпимо —
    через `raw_decode`, игнорируя текст после первого валидного объекта).
    При сбое формата (обрыв по `max_tokens` или иначе кривой JSON) повторяет
    с бОльшим `max_tokens` из списка `max_tokens_attempts` (по возрастанию).
    Возвращает распарсенный dict, либо `None` при неустранимом сбое (после
    всех попыток формата, или при сетевой/API-ошибке — там повтор смысла не
    имеет, это забота самого SDK).

    Не проверяет обязательные ключи схемы — это ответственность вызывающего
    кода конкретной роли (у каждой роли свой набор обязательных ключей)."""
    for attempt, max_tokens in enumerate(max_tokens_attempts, start=1):
        is_last = attempt == len(max_tokens_attempts)
        response = None
        try:
            response = client.messages.create(
                model=model,
                max_tokens=max_tokens,
                system=system_prompt,
                messages=[{"role": "user", "content": user_content}],
                timeout=_request_timeout(max_tokens),
            )
            raw = "".join(
                block.text for block in response.content if getattr(block, "type", "") == "text"
            )
            raw = strip_json_fences(raw)
            data, _ = json.JSONDecoder().raw_decode(raw)
            return data

        except (json.JSONDecodeError, ValueError) as exc:
            stop_reason = getattr(response, "stop_reason", "?") if response is not None else "?"
            ctx = f" ({log_ctx})" if log_ctx else ""
            # 26.09.2026 — третий реальный сбой на этой же роли (Отборщик):
            # "Expecting value: line 1 column 1 (char 0)" повторился даже на
            # max_tokens=6000, и это сообщение НЕ различает два совершенно
            # разных случая — (а) raw реально пустая строка (например, весь
            # бюджет токенов ушёл на блок типа не "text", скажем "thinking",
            # и до текстового блока с JSON модель просто не добралась), или
            # (б) raw непустая, но начинается не с JSON (модель начала
            # ответ с преамбулы/рассуждений вместо прямого "{"). Без этого
            # лога нельзя было бы отличить одно от другого и чинить
            # прицельно, а не гадать в третий раз — поэтому здесь логируется
            # состав блоков ответа и превью самого текста.
            block_types = (
                [getattr(b, "type", "?") for b in response.content]
                if response is not None else []
            )
            raw_preview = repr(raw[:200])
            if not is_last:
                next_max = max_tokens_attempts[attempt]
                logger.warning(
                    "%s%s: сбой формата ответа при max_tokens=%s (stop_reason=%s, "
                    "блоки_ответа=%s, превью=%s) — похоже на обрыв по лимиту токенов, "
                    "повтор с max_tokens=%s: %s",
                    role_name, ctx, max_tokens, stop_reason, block_types, raw_preview, next_max, exc,
                )
                continue
            logger.error(
                "%s%s: сбой формата ответа после повтора (max_tokens=%s, stop_reason=%s, "
                "блоки_ответа=%s, превью=%s): %s",
                role_name, ctx, max_tokens, stop_reason, block_types, raw_preview, exc,
            )
            return None

        except Exception as exc:
            # сетевые/API-ошибки — повтор с другим max_tokens тут ни при чём,
            # свои повторы уже делает сам anthropic SDK, сдаёмся сразу
            ctx = f" ({log_ctx})" if log_ctx else ""
            logger.error("%s%s: ошибка вызова: %s", role_name, ctx, exc)
            return None

    return None
