def _format_story(story: dict, notes_by_id: dict) -> str:
    lines = [f"### Сюжет: {story['title']} (важность {story.get('combined_importance', '?')})"]
    # 03.10.2026 — подсказки Отборщика (см. его промпт, шаги 4-5). ru_angle —
    # его гипотеза о канале влияния на российского читателя (НЕ факт, не
    # источник: для source_id не годится — см. правило 15 промпта); new_fact
    # — что нового по сравнению с прошлыми выпусками (правило 16).
    if story.get("ru_angle"):
        lines.append(f"подсказка отборщика (гипотеза, не факт): {story['ru_angle']}")
    if story.get("continuation") and story.get("new_fact"):
        lines.append(f"продолжение темы прошлых выпусков; новое: {story['new_fact']}")
    for note_id in story.get("note_ids", []):
        note = notes_by_id.get(note_id)
        if note is None:
            logger.warning("Аналитик: note_id %s из Отборщика не найден в архиве", note_id)
            continue
        lines.append(
            f"- source_id={note_id} | источник={note['source']} | ссылка={note['link']} "
            f"| глубина={note['content_level']}\n"
            f"  факты: {' '.join(note.get('key_facts', []))}\n"
            f"  market_link: {note.get('market_link') or '—'}"
        )
    return "\n".join(lines)


def write_issue(
    stories: list[dict],
    notes_by_id: dict,
    history_summary: str = "",
    related_notes: list[str] | None = None,
    model: str | None = None,
    effort: str | None = None,
    thinking_override: str | None = None,
    on_usage=None,
) -> dict | None:
    """stories — отобранные Отборщиком сюжеты (selected_story_ids из его
    ответа, уже отфильтрованные вызывающим кодом). notes_by_id — {note_id:
    заметка Экстрактора} для всех note_ids, встречающихся в stories.
    history_summary/related_notes — см. docstring модуля про текущий
    ограниченный скоуп (оба опциональны). Возвращает JSON-черновик выпуска
    или None при неустранимой ошибке.

    26.09.2026, вечер — четыре новых необязательных параметра для
    `scripts/ab_test_analyst.py` (воскресный A/B, три модели), ни один не
    меняет поведение обычного вызова (dry_run_v2.py и т.п.), если не
    передан:
    - `model`/`effort` — переопределяют `config.MODEL_ANALYST`/
      `MODEL_ANALYST_EFFORT`. Нужно именно так, а не через переменные
      окружения: `config.py` читает `os.environ` один раз при импорте, а
      A/B-скрипт перебирает три разные модели за один процесс.
    - `thinking_override` — передаётся в `llm_json.call_json_role()` как
      есть (см. его докстринг). Единственное применение сегодня: Sonnet 5
      в A/B тестируется с `"adaptive"`, а не с дефолтным для него
      `"disabled"` — паритет с тем, как он реально работал бы в проде,
      если выиграет тест (поправка менеджера 26.09.2026). Отборщик
      (`selector.py`) этот параметр не получает и не должен — там
      thinking остаётся всегда `disabled`, вопрос паритета с продом там не
      стоит.
    - `on_usage` — см. `llm_json.call_json_role()`, тот же callback,
      прокинут без изменений."""
    if not stories:
        logger.info("Аналитик: нет отобранных сюжетов, пропускаем вызов")
        return None

    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=90.0)

    stories_block = "\n\n".join(_format_story(s, notes_by_id) for s in stories)

    history_block = (
        history_summary.strip() if history_summary and history_summary.strip()
        else "(история выпусков за 14 дней в этом запуске не передана — retrieval "
             "ещё не реализован, не полагайся на предыдущие выпуски, которых не видишь)"
    )
    related_block = (
        "\n".join(f"- {r}" for r in related_notes) if related_notes
        else "(релевантные заметки по тегам из архива в этом запуске не передавались)"
    )

    user_content = (
        f"Отобранные сюжеты выпуска:\n\n{stories_block}\n\n"
        f"История выпусков за 14 дней:\n{history_block}\n\n"
        f"Релевантные заметки/выпуски из архива по тегам:\n{related_block}\n"
    )

    # 26.09.2026 — по факту первого DRY_RUN (см. src/llm_json.py, docstring
    # модуля) — обрыв по max_tokens посреди JSON у остальных трёх ролей
    # оказался реальной проблемой, а не гипотетической; здесь вход (полные
    # тексты нескольких сюжетов) не меньше, чем у Отборщика, так что бюджет
    # тоже расширен профилактически, не дожидаясь отдельного падения именно
    # этой роли. Третий, самый большой уровень (14000) — запас на случай
    # Opus 5.5/Fable 5.1 (воскресный A/B): у них thinking обязателен и ест
    # тот же max_tokens (см. src/llm_json.py, шестой пункт), а effort ниже
    # это не гарантирует полностью — лучше запас, чем повторный сбой по
    # тому же классу проблемы, что и обрыв на кириллице.
    use_model = model or config.MODEL_ANALYST
    use_effort = effort if effort is not None else config.MODEL_ANALYST_EFFORT

    data = call_json_role(
        client, use_model, SYSTEM_PROMPT, user_content,
        max_tokens_attempts=[3500, 7000, 14000],
        role_name="Аналитик",
        effort=use_effort,
        thinking_override=thinking_override,
        on_usage=on_usage,
    )
    if data is None:
        return None

    missing = _REQUIRED_KEYS - set(data.keys())
    if missing:
        logger.error("Аналитик: в ответе нет ключей %s", missing)
        return None
    return data
