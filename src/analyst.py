"""
Аналитик (v2, роль 3) — дважды в день, пишет черновик выпуска целиком
(hook + блоки + watch_next) по отобранным Отборщиком сюжетам. Промпт
закреплён после двух раундов ревью — см. claude/format-v2-prompts-draft.md
(третья версия, раздел 3).

МОДЕЛЬ (config.MODEL_ANALYST): по брифу должна быть Opus 5.5, точный
идентификатор не подтверждён на 26.09.2026 — см. комментарий у константы
в src/config.py. Сейчас временно Sonnet 5, переключить одной правкой
config.py после подтверждения id / результата A/B.

СКОУП ЭТОЙ ВЕРСИИ (важно не молчать об этом): «Вход» по документу — это
ещё «сжатая история выпусков за 14 дней» и «до 10 релевантных заметок/
выпусков из архива по тегам». Обе части — сами по себе отдельная нерешённая
задача (как именно сжимать 14 дней истории — отдельным LLM-вызовом? просто
заголовками? когда именно на неё тратить токены), поэтому в этой первой
версии кода они реализованы как НЕОБЯЗАТЕЛЬНЫЕ параметры функции
(history_summary, related_notes) — если их не передать, промпту явно
говорится, что этой части контекста в этом запуске нет, а не молчаливо
подставляется пустота. write_issue() уже готов принять их, как только
retrieval/compression-логика появится отдельным кодом (не входит в
сегодняшний объём работы — см. сообщение автору/менеджеру)."""

import json
import logging

import anthropic

from . import config

logger = logging.getLogger(__name__)


SYSTEM_PROMPT = """\
Ты пишешь аналитический выпуск для Telegram-канала «О чём talk'уют
деньги» — разбор главных экономических событий дня для читателя из
России, простым языком, с лёгкой иронией, без канцелярита и
профессионального жаргона.

Верни JSON:
{
  "hook": "...",      // 1-2 предложения, главная мысль дня — читатель
                       // видит их в уведомлении, от них зависит, откроют
                       // ли выпуск
  "hook_block_refs": [...],   // индексы блоков (0-based), на фактах
                               // которых держится hook — hook не привязан
                               // к одному блоку напрямую, поэтому источники
                               // указываются так, а не через source_ids
  "blocks": [
    {
      "title": "...",
      "what": "...",        // факты с точными цифрами
      "meaning": "...",     // что это значит и для кого — явная
                             // интерпретация, не факт
      "link": "..." | null, // связь с другим блоком, если есть
      "source_ids": [...]
    }, ...
  ],
  "watch_next": "...",           // что смотреть дальше — заседания, данные, решения
  "watch_next_source_ids": [...] // source_id заметок, из которых взято
                                  // упомянутое в watch_next (если там
                                  // названы конкретные даты/события из
                                  // источников, а не общая формулировка)
}

Обязательные правила:
1. У КАЖДОГО фактического утверждения В ЛЮБОМ ПОЛЕ (hook, what, meaning,
   link, watch_next) должен быть конкретный source_id, из которого оно
   взято. Нет факта ни в одной заметке/статье — не пиши его. Для hook
   источники указываются через `hook_block_refs` (номера блоков, чьими
   фактами подтверждён hook) — hook должен быть прямым следствием фактов
   из этих блоков, а не отдельным, более сильным или более общим
   утверждением, чем то, что реально в них есть. Для watch_next, если там
   названо конкретное событие/дата из источника (а не общая формулировка
   без цифр) — укажи через `watch_next_source_ids`.
2. "meaning" — это интерпретация, а не факт. Формулируй её явно как взгляд
   редакции ("на наш взгляд", "похоже, что", "вероятно"), не выдавай
   предположение за установленный факт.
3. Любое число, сумма, процент, дата (включая даты будущих событий —
   заседаний, отчётов, решений) — ТОЛЬКО из предоставленных источников, в
   любом поле. Никогда не дополняй по собственным знаниям модели (например
   точный текущий уровень ставки ФРС, дату следующего заседания, если её
   не было в тексте источника). Если в источниках нет точной даты/значения
   для watch_next — пиши обобщённо, без выдуманной даты ("ближайшее
   заседание ФРС", а не конкретное число, которого не было в источниках).
4. Точные цифры бери из заметок уровня content_level="full" там, где это
   возможно. Если у сюжета есть заметки разной глубины (full/lead/
   headline) — используй lead/headline только для контекста и общей
   картины, а не как источник точного числа, если то же число есть в
   заметке уровня full.
5. Простой язык, минимум профессионального жаргона; термин, если без него
   нельзя, поясняется на ходу двумя-тремя словами.
6. Аббревиатуры организаций — полное русское название или только
   устоявшиеся ФРС/ЕЦБ/ЦБ РФ; не оставляй иностранные аббревиатуры
   латиницей без расшифровки.
7. Пиши с точки зрения российского читателя: никогда не используй "наш"/
   "у нас"/"здесь"/"дома" применительно к рынку/ставке/экономике конкретной
   страны — всегда явно называй её ("рынок США", "ставка ФРС", а не "наш
   рынок"). Правило одинаково касается и иностранных, и российских
   сюжетов — если из контекста не абсолютно очевидно, что речь о России,
   называй страну прямо.
8. Военные события упоминаются ТОЛЬКО как причина экономического эффекта
   (санкции, влияние на сырьё, логистику, торговлю) — без собственных
   оценок конфликта и без пересказа боевых действий как таковых. Если у
   сюжета нет прямого экономического следствия военной темы — не пиши про
   неё вообще, даже фоном.
9. Перевод чисел и единиц: billion = миллиард, trillion = триллион; bps =
   базисные пункты (50 bps = 0,5 п.п.); валюту не пересчитывай — $
   остаётся $, не переводи в рубли/евро; десятичная запятая, знак числа не
   меняй (не путай рост со снижением при переводе).
10. Относительные даты: называй день недели или конкретную дату ("в
    четверг", "23 сентября"), не "вчера"/"сегодня" — выпуск читают в 08:00
    или 19:00 МСК про события, которые в США могли произойти вечером
    накануне, и относительные слова легко путают, о каком дне речь.
11. Сарказм/ирония допустимы, только если не меняют и не преувеличивают
    факт.
12. "link" между блоками — только реальная содержательная связь; не
    притягивай её ради красивого перехода.
13. Заголовок блока — короткий, с жирным выделением (Telegram HTML,
    <b>...</b>), чтобы выпуск можно было пробежать глазами.
14. Целься в общий объём ≤3500 символов на весь выпуск — если материала
    много, выбирай самое существенное, а не сокращай каждый факт до
    нечитаемой плотности."""

_REQUIRED_KEYS = {"hook", "hook_block_refs", "blocks", "watch_next", "watch_next_source_ids"}


def _format_story(story: dict, notes_by_id: dict) -> str:
    lines = [f"### Сюжет: {story['title']} (важность {story.get('combined_importance', '?')})"]
    for note_id in story.get("note_ids", []):
        note = notes_by_id.get(note_id)
        if note is None:
            logger.warning("Аналитик: note_id %s из Отборщика не найден в архиве", note_id)
            continue
        lines.append(
            f"- source_id={note_id} | источник={note['source']} | ссылка={note['link']} "
            f"| глубина={note['content_level']}\n"
            f"  факты: {' '.join(note.get('key_facts', []))}\n"
            f"  market_link: {note.get('market_link') or '—'}"
        )
    return "\n".join(lines)


def write_issue(
    stories: list[dict],
    notes_by_id: dict,
    history_summary: str = "",
    related_notes: list[str] | None = None,
) -> dict | None:
    """stories — отобранные Отборщиком сюжеты (selected_story_ids из его
    ответа, уже отфильтрованные вызывающим кодом). notes_by_id — {note_id:
    заметка Экстрактора} для всех note_ids, встречающихся в stories.
    history_summary/related_notes — см. docstring модуля про текущий
    ограниченный скоуп (оба опциональны). Возвращает JSON-черновик выпуска
    или None при неустранимой ошибке."""
    if not stories:
        logger.info("Аналитик: нет отобранных сюжетов, пропускаем вызов")
        return None

    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=90.0)

    stories_block = "\n\n".join(_format_story(s, notes_by_id) for s in stories)

    history_block = (
        history_summary.strip() if history_summary and history_summary.strip()
        else "(история выпусков за 14 дней в этом запуске не передана — retrieval "
             "ещё не реализован, не полагайся на предыдущие выпуски, которых не видишь)"
    )
    related_block = (
        "\n".join(f"- {r}" for r in related_notes) if related_notes
        else "(релевантные заметки по тегам из архива в этом запуске не передавались)"
    )

    user_content = (
        f"Отобранные сюжеты выпуска:\n\n{stories_block}\n\n"
        f"История выпусков за 14 дней:\n{history_block}\n\n"
        f"Релевантные заметки/выпуски из архива по тегам:\n{related_block}\n"
    )

    try:
        response = client.messages.create(
            model=config.MODEL_ANALYST,
            max_tokens=3000,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_content}],
        )
        raw = "".join(
            block.text for block in response.content if getattr(block, "type", "") == "text"
        ).strip()

        if raw.startswith("```"):
            raw = raw.strip("`")
            raw = raw.split("\n", 1)[1] if "\n" in raw else raw
            if raw.lower().startswith("json"):
                raw = raw[4:]

        data, _ = json.JSONDecoder().raw_decode(raw)
        missing = _REQUIRED_KEYS - set(data.keys())
        if missing:
            raise ValueError(f"В ответе Аналитика нет ключей: {missing}")
        return data

    except (json.JSONDecodeError, ValueError) as exc:
        logger.error("Сбой формата ответа Аналитика: %s", exc)
        return None
    except Exception as exc:
        logger.error("Ошибка вызова Аналитика: %s", exc)
        return None
