"""
Отборщик (v2, роль 2) — Sonnet 5, дважды в день: группирует заметки в
сюжеты по смыслу и отбирает 3-5 главных для выпуска. Промпт закреплён
после двух раундов ревью — см. claude/format-v2-prompts-draft.md (третья
версия, раздел 2).

Вход по документу — «все заметки с прошлого выпуска, importance ≥ 3» и
«заголовки сюжетов двух последних выпусков»; фильтр по importance и
подготовку lookback-заголовков делает вызывающий код (scripts/dry_run_v2.py),
не эта функция — select_stories() ожидает уже отфильтрованный список.
"""

import logging

import anthropic

from . import config
from .llm_json import call_json_role

logger = logging.getLogger(__name__)


SYSTEM_PROMPT = """\
Ты — редактор-отборщик для аналитического выпуска Telegram-канала
«О чём talk'уют деньги». Тебе дают список заметок за период с прошлого
выпуска — они уже прошли программную проверку на дубли по ссылке и по
текстовому сходству, так что явные повторы одного источника или
почти дословные совпадения среди них уже не встретятся. Тебе также дают
заголовки сюжетов двух последних выпусков — для проверки повторов (см.
шаг 4). Твоя задача — сгруппировать оставшиеся заметки в сюжеты по СМЫСЛУ
(одно и то же событие, разными словами и с разных углов) и отобрать
главные для сегодняшнего выпуска.

Шаг 1 — группировка. Объедини заметки, которые описывают ОДНО И ТО ЖЕ
событие, даже если из разных источников и под разными углами подачи.
Критерий — совпадает ли конкретное событие (то же решение того же
регулятора, тот же отчёт той же компании, тот же контракт), а не просто
тема или похожий набор упомянутых сущностей. Два ПОХОЖИХ, но РАЗНЫХ
событий (например, ФРС и Банк Англии оба подняли ставку на 50 базисных
пунктов в одну неделю, или доходность 5-летних и 10-летних облигаций) —
это разные сюжеты, даже если формулировки почти совпадают, и даже если
совпадает конкретное число (ставка, процент, сумма) — само по себе общее
число ничего не доказывает, если оно относится к разным показателям. Один
источник, разбивший одно событие на несколько заметок под разными
заголовками (решение + реакция рынка + прогноз) — это ОДИН сюжет.

Шаг 2 — военная тема. Не отбирай сюжеты, суть которых — военные действия
(бои, удары, потери, ход конфликта). Если у сюжета есть прямое
экономическое следствие (санкции, влияние на сырьё/логистику/торговлю) —
подача строится ТОЛЬКО через это следствие, а не через военную сторону
события. Если экономического следствия нет — сюжет не отбирается вовсе,
независимо от importance отдельных заметок.

Шаг 3 — качество опоры. Не строй сюжет исключительно на заметках с
content_level="headline" (заголовок без лида и текста) — такая заметка
слишком ненадёжна как единственная опора сюжета. Если у сюжета есть хотя
бы одна заметка уровня "lead" или "full" — можно отбирать; если все
заметки сюжета headline-only — такой сюжет по возможности не выбирай в
selected_story_ids, если есть другие, лучше подтверждённые сюжеты на замену.

Шаг 4 — повтор относительно прошлых выпусков. Сравни получившиеся сюжеты с
заголовками сюжетов двух последних выпусков. Если сюжет прошлого выпуска
продолжается СЕГОДНЯ без нового факта (просто те же заметки или пересказ
того же самого без развития) — не отбирай его повторно. Если появился
именно новый факт по теме прошлого выпуска (новое решение, новая цифра,
новый эпизод) — можно отобрать, но пометь его как продолжение
(`"continuation": true` в выходном JSON).

Шаг 5 — ранжирование. Из получившихся сюжетов (прошедших шаги 2-4) выбери
3-5 главных. Критерии: масштаб рыночного эффекта, суммарная важность
заметок сюжета, актуальность для российского читателя (не обязательно про
Россию — про то, что реально её касается: сырьё, санкции, ставки,
торговля). Не выбирай сюжет только из-за высокого importance отдельной
заметки — учитывай, есть ли по нему содержательно что сказать (минимум 2-3
достаточных факта).

Шаг 6 — связка. Если между выбранными сюжетами есть РЕАЛЬНАЯ содержательная
связь (например, решение ФРС и последовавшая реакция рынка нефти) —
отметь её. Если связи по существу нет — не выдумывай её ради красивого
перехода, оставь пустой.

Верни JSON:
{
  "stories": [
    {
      "story_id": "...",
      "note_ids": [...],
      "title": "...",
      "combined_importance": 1-5,
      "continuation": true | false,   // продолжает сюжет одного из
                                       // двух последних выпусков с новым
                                       // фактом
      "why_grouped": "..."   // для отладки, в канал не идёт
    }, ...
  ],
  "selected_story_ids": [...],   // 3-5 главных, по убыванию важности
  "connection": {"story_ids": [...], "note": "..."} | null
}"""

_REQUIRED_KEYS = {"stories", "selected_story_ids", "connection"}


def _format_notes(notes: list[dict]) -> str:
    lines = []
    for note in notes:
        lines.append(
            f"- id={note['id']} | источник={note['source']} | важность={note['importance']} "
            f"| глубина={note['content_level']} | регион={note.get('region', '')} | "
            f"теги={','.join(note.get('tags_en', []))}\n"
            f"  факты: {' '.join(note.get('key_facts', []))}"
        )
    return "\n".join(lines)


def select_stories(notes: list[dict], last_issue_titles: list[str]) -> dict | None:
    """notes — заметки (уже отфильтрованные вызывающим кодом по
    importance >= config.V2_SELECTOR_MIN_IMPORTANCE), каждая — полный ответ
    Экстрактора + служебные id/source/link. last_issue_titles — плоский
    список заголовков сюжетов последних config.V2_SELECTOR_LOOKBACK_ISSUES
    выпусков (см. archive.load_last_issue_titles), может быть пустым (первый
    запуск v2 — нормальный случай). Возвращает JSON-ответ Отборщика или None
    при неустранимой ошибке."""
    if not notes:
        logger.info("Отборщик: нет заметок с importance >= %s, пропускаем вызов", config.V2_SELECTOR_MIN_IMPORTANCE)
        return {"stories": [], "selected_story_ids": [], "connection": None}

    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=60.0)

    lookback_block = (
        "\n".join(f"- {t}" for t in last_issue_titles)
        if last_issue_titles else "(нет — это один из первых выпусков v2)"
    )
    user_content = (
        f"Заметки за период с прошлого выпуска:\n{_format_notes(notes)}\n\n"
        f"Сюжеты двух последних выпусков (для шага 4):\n{lookback_block}\n"
    )

    # 26.09.2026 — первый реальный DRY_RUN: при max_tokens=2000 и 37 заметках
    # на входе ответ обрывался настолько рано, что текстового блока не
    # набралось вообще ("Expecting value: line 1 column 0" — пустая строка).
    # См. src/llm_json.py про повтор с бОльшим max_tokens вместо укорачивания
    # входа — здесь вход и так уже отфильтрован по importance вызывающим
    # кодом, дальше сокращать нечего.
    data = call_json_role(
        client, config.MODEL_SELECTOR, SYSTEM_PROMPT, user_content,
        max_tokens_attempts=[3000, 6000],
        role_name="Отборщик",
    )
    if data is None:
        return None

    missing = _REQUIRED_KEYS - set(data.keys())
    if missing:
        logger.error("Отборщик: в ответе нет ключей %s", missing)
        return None
    return data
