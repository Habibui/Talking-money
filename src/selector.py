"""
Отборщик (v2, роль 2) — Sonnet 5, дважды в день: группирует заметки в
сюжеты по смыслу и отбирает 3-5 главных для выпуска. Промпт закреплён
после двух раундов ревью — см. claude/format-v2-prompts-draft.md (третья
версия, раздел 2).

Вход по документу — «все заметки с прошлого выпуска, importance ≥ 3» и
«заголовки сюжетов двух последних выпусков»; фильтр по importance и
подготовку lookback-заголовков делает вызывающий код (scripts/dry_run_v2.py),
не эта функция — select_stories() ожидает уже отфильтрованный список.
"""

import logging

import anthropic

from . import config
from .llm_json import call_json_role

logger = logging.getLogger(__name__)


SYSTEM_PROMPT = """\
Ты — редактор-отборщик для аналитического выпуска Telegram-канала
«О чём talk'уют деньги». Тебе дают список заметок за период с прошлого
выпуска — они уже прошли программную проверку на дубли по ссылке и по
текстовому сходству, так что явные повторы одного источника или
почти дословные совпадения среди них уже не встретятся. Тебе также дают
краткое содержание трёх последних выпусков — для проверки повторов (см.
шаг 4). Твоя задача — сгруппировать оставшиеся заметки в сюжеты по СМЫСЛУ
(одно и то же событие, разными словами и с разных углов) и отобрать
главные для сегодняшнего выпуска.

Шаг 1 — группировка. Объедини заметки, которые описывают ОДНО И ТО ЖЕ
событие, даже если из разных источников и под разными углами подачи.
Критерий — совпадает ли конкретное событие (то же решение того же
регулятора, тот же отчёт той же компании, тот же контракт), а не просто
тема или похожий набор упомянутых сущностей. Два ПОХОЖИХ, но РАЗНЫХ
событий (например, ФРС и Банк Англии оба подняли ставку на 50 базисных
пунктов в одну неделю, или доходность 5-летних и 10-летних облигаций) —
это разные сюжеты, даже если формулировки почти совпадают, и даже если
совпадает конкретное число (ставка, процент, сумма) — само по себе общее
число ничего не доказывает, если оно относится к разным показателям. Один
источник, разбивший одно событие на несколько заметок под разными
заголовками (решение + реакция рынка + прогноз) — это ОДИН сюжет.
Обратное тоже верно: рыночный обзор дня («Nasdaq вырос, доходности
выросли, нефть упала, хедж-фонды проиграли на французских облигациях»)
— это НЕ один сюжет, а несколько несвязанных; не склеивай разнородные
факты в один сюжет только потому, что они случились в один день на одном
рынке. Если из такого обзора нужен один факт — оформи его отдельным сюжетом
или не бери вовсе.

Шаг 2 — военная тема. Не отбирай сюжеты, суть которых — военные действия
(бои, удары, потери, ход конфликта). Если у сюжета есть прямое
экономическое следствие (санкции, влияние на сырьё/логистику/торговлю) —
подача строится ТОЛЬКО через это следствие, а не через военную сторону
события. Если экономического следствия нет — сюжет не отбирается вовсе,
независимо от importance отдельных заметок.

Шаг 3 — качество опоры. Не строй сюжет исключительно на заметках с
content_level="headline" (заголовок без лида и текста) — такая заметка
слишком ненадёжна как единственная опора сюжета. Если у сюжета есть хотя
бы одна заметка уровня "lead" или "full" — можно отбирать; если все
заметки сюжета headline-only — такой сюжет по возможности не выбирай в
selected_story_ids, если есть другие, лучше подтверждённые сюжеты на замену.

Шаг 4 — повтор относительно прошлых выпусков. Тебе дано краткое
содержание блоков трёх последних выпусков (дата, заголовок, начало с
цифрами). Сравнивай по СУТИ и по цифрам, а не по заголовкам: одна и та же
история у разных изданий звучит под разными заголовками («доходности на
максимумах», «распродажа облигаций», «Treasury yields at generational
highs» — это одна и та же тема, и если она уже была в любом из трёх
последних выпусков, сегодняшняя заметка без НОВОГО КОНКРЕТНОГО ФАКТА — не
сюжет). Новый факт — это новая цифра, новое решение, новый участник или
новое последствие, которых нет в тексте прошлого выпуска; та же мысль
другими словами и «ситуация сохраняется» новым фактом не являются. Если
новый факт есть — сюжет можно отобрать, но пометь `"continuation": true` и
в поле `new_fact` одной фразой напиши, ЧТО именно нового (Аналитик построит
блок на этом, а не на пересказе старого). Если нового факта нет — не
отбирай, даже при высокой важности.

Шаг 5 — вектор канала и ранжирование. Канал пишет о том, что меняет деньги
российского читателя: курс рубля, цены на нефть и газ (бюджет и экспорт
России), решения ЦБ РФ и Минфина, ставки и доходности в США/Европе в той
мере, в какой они двигают рубль, вклады и кредиты, санкции и торговые
войны, цены на то, что Россия покупает и продаёт, крупные российские
компании и банки. Для КАЖДОГО сюжета (не только отобранного) поставь:
  - `ru_relevance` от 0 до 3: 0 — связи с этим вектором нет; 1 — только
    общий фон («мировая экономика», «настроения инвесторов»); 2 — есть
    понятный конкретный канал, по которому событие доходит до рубля/нефти/
    ставок/цен/вкладов россиян; 3 — прямо про Россию или сильнейший мировой
    драйвер для неё (нефть, санкции, ФРС, доллар).
  - `ru_angle` — ОДНА конкретная фраза: по какому каналу это дойдёт до
    россиянина (например «дороже нефть → больше валюты у экспортёров →
    крепче рубль»). Если не получается написать такую фразу без натяжки и
    общих слов — значит ru_relevance не выше 1. Фраза — твоя гипотеза, не
    факт, и в канал не идёт; её увидит Аналитик как подсказку.
Пример шкалы: решение ФРС по ставке — 3; рекордная доходность американских
облигаций — 2 (двигает доллар и мировые ставки); ставка центробанка малой
открытой экономики (Австралия, Новая Зеландия) — 1, если из фактов не
следует мирового эффекта; прогноз счетов за газ для домохозяйств в одной
европейской стране — 1; оценка акций люксовых брендов — 0-1; корпоративная
история без рыночного масштаба — 0-1.
В selected_story_ids попадают ТОЛЬКО сюжеты с ru_relevance 2 или 3 и только
свежие (если из текста заметок видно, что событие произошло больше двух
суток назад и ничего нового по нему нет — не отбирай; у заметок указан
возраст). Среди таких выбери от 0 до 4 главных: масштаб рыночного эффекта,
суммарная важность заметок, связь с российским читателем. Количество — не
цель. Два сильных сюжета лучше четырёх, из которых два «для заполнения»;
если сильных нет вообще — верни пустой selected_story_ids, это нормальный
результат (пустой день, выходные). Не выбирай сюжет только из-за высокого
importance отдельной заметки — учитывай, есть ли по нему содержательно что
сказать (минимум 2-3 достаточных факта, а не одна строка из заголовка).

Шаг 6 — связка. Если между выбранными сюжетами есть РЕАЛЬНАЯ содержательная
связь (например, решение ФРС и последовавшая реакция рынка нефти) —
отметь её. Если связи по существу нет — не выдумывай её ради красивого
перехода, оставь пустой.

Верни JSON:
{
  "stories": [
    {
      "story_id": "...",
      "note_ids": [...],
      "title": "...",
      "combined_importance": 1-5,
      "ru_relevance": 0-3,
      "ru_angle": "...",              // одна конкретная фраза, см. шаг 5
      "continuation": true | false,   // продолжает сюжет одного из
                                       // трёх последних выпусков с новым
                                       // фактом
      "new_fact": "..." | null,       // что именно нового, если continuation
      "why_grouped": "..."   // для отладки, в канал не идёт
    }, ...
  ],
  "selected_story_ids": [...],   // 0-4 главных, по убыванию важности
  "connection": {"story_ids": [...], "note": "..."} | null
}"""

_REQUIRED_KEYS = {"stories", "selected_story_ids", "connection"}


def _format_age(card: dict) -> str:
    from . import archive
    hours = archive.note_age_hours(card)
    return f"{round(hours)}ч" if hours < 48 else f"{round(hours / 24)}дн"


def _format_notes(notes: list[dict]) -> str:
    lines = []
    for note in notes:
        lines.append(
            f"- id={note['id']} | источник={note['source']} | важность={note['importance']} "
            f"| возраст={_format_age(note)} | глубина={note['content_level']} "
            f"| регион={note.get('region', '')} | "
            f"теги={','.join(note.get('tags_en', []))}\n"
            f"  факты: {' '.join(note.get('key_facts', []))}"
        )
    return "\n".join(lines)


def select_stories(
    notes: list[dict],
    last_issue_titles: list[str],
    last_issue_context: list[str] | None = None,
) -> dict | None:
    """notes — заметки (уже отфильтрованные вызывающим кодом по
    importance >= config.V2_SELECTOR_MIN_IMPORTANCE и по свежести, см.
    archive.filter_fresh), каждая — полный ответ Экстрактора + служебные
    id/source/link. last_issue_titles — плоский список заголовков сюжетов
    последних config.V2_SELECTOR_LOOKBACK_ISSUES выпусков (см.
    archive.load_last_issue_titles), может быть пустым (первый запуск v2 —
    нормальный случай). last_issue_context — 03.10.2026: то же, но с началом
    текста каждого блока (archive.load_last_issue_summaries); если передан,
    используется ВМЕСТО заголовков (там заголовки уже есть). Необязателен —
    старые вызовы (dry_run_v2.py, ab_test_analyst.py) продолжают работать
    как раньше. Возвращает JSON-ответ Отборщика или None при неустранимой
    ошибке."""
    if not notes:
        logger.info("Отборщик: нет заметок с importance >= %s, пропускаем вызов", config.V2_SELECTOR_MIN_IMPORTANCE)
        return {"stories": [], "selected_story_ids": [], "connection": None}

    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=60.0)

    lookback_lines = last_issue_context if last_issue_context else last_issue_titles
    lookback_block = (
        "\n".join(f"- {t}" for t in lookback_lines)
        if lookback_lines else "(нет — это один из первых выпусков v2)"
    )
    user_content = (
        f"Заметки за период с прошлого выпуска:\n{_format_notes(notes)}\n\n"
        f"Содержание трёх последних выпусков (для шага 4):\n{lookback_block}\n"
    )

    # 26.09.2026 — первый реальный DRY_RUN: при max_tokens=2000 и 37 заметках
    # на входе ответ обрывался настолько рано, что текстового блока не
    # набралось вообще ("Expecting value: line 1 column 0" — пустая строка).
    # См. src/llm_json.py про повтор с бОльшим max_tokens вместо укорачивания
    # входа — здесь вход и так уже отфильтрован по importance вызывающим
    # кодом, дальше сокращать нечего.
    data = call_json_role(
        client, config.MODEL_SELECTOR, SYSTEM_PROMPT, user_content,
        max_tokens_attempts=[4500, 9000],
        role_name="Отборщик",
    )
    if data is None:
        return None

    missing = _REQUIRED_KEYS - set(data.keys())
    if missing:
        logger.error("Отборщик: в ответе нет ключей %s", missing)
        return None

    for story in data.get("stories", []):
        rel = story.get("ru_relevance")
        if isinstance(rel, bool) or not isinstance(rel, int) or not 0 <= rel <= 3:
            # Не выдумываем оценку за модель и не отсекаем сюжет молча —
            # см. apply_gates: сюжет без оценки проходит, но это в логе.
            if rel is not None:
                logger.warning("Отборщик: ru_relevance=%r у сюжета %r вне 0-3 — игнорируем", rel, story.get("story_id"))
            story["ru_relevance"] = None
    return data


def apply_gates(selection: dict) -> tuple[list[dict], list[str]]:
    """03.10.2026 — программный фильтр поверх выбора Отборщика (промпт сам по
    себе вектор канала не удержал, см. config.V2_SELECTOR_MIN_RU_RELEVANCE).
    Возвращает (сюжеты для Аналитика в порядке selected_story_ids — то есть
    по убыванию важности, не более 4 — потолок блоков Аналитика; список
    строк «что отсечено и почему» для лога/сообщения автору). Сюжет без
    оценки ru_relevance не отсекается: сбой формата ответа не должен
    молча обнулять выпуск, но предупреждение остаётся в логе."""
    by_id = {s["story_id"]: s for s in selection.get("stories", []) if "story_id" in s}
    kept, dropped = [], []
    for sid in selection.get("selected_story_ids", []):
        story = by_id.get(sid)
        if story is None:
            continue
        rel = story.get("ru_relevance")
        if rel is None:
            logger.warning("Отборщик: у сюжета %r нет ru_relevance — пропускаем без фильтра", story.get("title"))
        elif rel < config.V2_SELECTOR_MIN_RU_RELEVANCE:
            dropped.append(f"{story.get('title')} (связь с российским читателем {rel} из 3)")
            continue
        kept.append(story)
    return kept[:4], dropped
