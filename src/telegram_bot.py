"""
Публикация сообщения в канал через Telegram Bot API.
"""

import html
import logging
import re

import requests

from . import config

logger = logging.getLogger(__name__)

# Лимит Telegram на длину text у sendMessage — 4096 символов (считая HTML-разметку
# в самой строке). Дайджест из нескольких новостей может в него не влезть —
# тогда режем на несколько сообщений подряд.
TELEGRAM_TEXT_LIMIT = 4096


def _esc(text: str) -> str:
    return html.escape(text or "", quote=False)


# 01.10.2026 — решение автора: модель (src/llm.py, SYSTEM_PROMPT, правило 4)
# выделяет главную мысль comment_ru текстовым маркером **вот так**, а не
# HTML-тегом напрямую — безопаснее (модель никогда не пишет сырой HTML,
# который нужно было бы доверять как есть), и один и тот же маркер работает
# одинаково что в одиночном посте, что в строке дайджеста. Применять ПОСЛЕ
# _esc() — звёздочки не экранируются html.escape(), так что порядок
# "сначала экранировать, потом заменить маркер на <b>" ничего не ломает.
# Пары ищем нежадно (.+?) — промпт просит не больше одной пары на
# comment_ru, но если модель всё же поставит несколько, все валидные пары
# просто станут жирными, а не одна случайная половина разметки.
_BOLD_MARKER_RE = re.compile(r"\*\*(.+?)\*\*")


def _apply_bold_marker(escaped_text: str) -> str:
    return _BOLD_MARKER_RE.sub(r"<b>\1</b>", escaped_text)


def _news_block(source: str, headline_ru: str, comment_ru: str, link: str) -> str:
    # 03.10.2026 — решение автора: возврат к исходному формату одиночного
    # поста (отдельный жирный заголовок + комментарий ниже) — 01.10.2026
    # была короткая попытка слить headline_ru и comment_ru в один абзац без
    # отдельного жирного заголовка (см. llm.py, правило 3 — там тоже
    # отменено), через два дня решили вернуть как было. Жирным выделяется и
    # headline целиком (как заголовок), и, отдельно, конкретная мысль ВНУТРИ
    # comment_ru через **маркер** (см. _apply_bold_marker выше) — это не
    # конфликтует: одно — заголовок блока, другое — акцент внутри текста.
    headline = _esc(headline_ru)
    comment = _apply_bold_marker(_esc(comment_ru))
    source_esc = _esc(source)
    return (
        f"<b>{headline}</b>\n\n"
        f"{comment}\n\n"
        f'<a href="{link}">{source_esc} →</a>'
    )


def build_message(item: dict, translated: dict) -> str:
    return _news_block(item["source"], translated["headline_ru"], translated["comment_ru"], item["link"])


# 30.09.2026 — фиксированный набор тем дайджеста (решение автора, п.3) —
# код держит соответствие тег→эмодзи, а не модель: модель (src/llm.py,
# SYSTEM_PROMPT, правило 11) выбирает только текстовый код темы
# (topic_tag), никогда сам символ эмодзи — так одна опечатка модели не
# протащит в канал случайный/неразрешённый эмодзи. Ключи должны совпадать
# с llm.VALID_TOPIC_TAGS.
_DIGEST_TOPIC_EMOJI = {
    "oil_gas": "🛢",
    "energy": "⚡",
    "markets": "📈",
    "central_banks": "🏦",
    "geopolitics": "🌍",
    "russia": "🇷🇺",
}
_DIGEST_DEFAULT_EMOJI = _DIGEST_TOPIC_EMOJI["markets"]


def _digest_line(source: str, comment_text: str, link: str, topic_tag: str | None) -> str:
    """Формат одной новости внутри дайджеста (решение автора 30.09.2026,
    п.3) — БЕЗ заголовка статьи (headline_ru здесь сознательно не
    используется): эмодзи-тег темы + одна строка сути + источник как
    слово-ссылка. comment_text — это comment_digest_ru (короткая версия
    comment_ru специально для дайджеста, см. llm.py, правило 4, решение
    автора 03.10.2026) — у записей очереди до этого деплоя (или если модель
    не вернула поле) это поле отсутствует/пусто, и build_digest_message ниже
    сам подставляет comment_ru целиком как запасной вариант, см. его
    докстринг. topic_tag — код темы из llm.VALID_TOPIC_TAGS; None или
    незнакомое значение (например, у новости, поставленной в очередь ДО
    деплоя темы 30.09.2026) — безопасный дефолт _DIGEST_DEFAULT_EMOJI, а не
    ошибка. comment_text обычно начинается с **маркера** главной мысли (см.
    llm.py, правило 4) — та же _apply_bold_marker(), что и в одиночном
    посте, иначе в дайджесте остались бы видны сырые звёздочки."""
    emoji = _DIGEST_TOPIC_EMOJI.get(topic_tag, _DIGEST_DEFAULT_EMOJI)
    comment = _apply_bold_marker(_esc(comment_text))
    source_esc = _esc(source)
    return f'{emoji} {comment} — <a href="{link}">{source_esc}</a>'


def _digest_priority(it: dict) -> int:
    """03.10.2026, решение автора — порядок, в котором новости набираются в
    дайджест, когда их больше, чем влезает в одно сообщение (см.
    build_digest_message ниже). Берутся не "первые по очереди" (как было до
    этого решения), а по эффективному приоритету: importance (1..5, см.
    llm.py, правило 12; отсутствует/невалидно — дефолт 3, та же логика, что
    и в llm.translate_and_comment) плюс +10 за каждый раз, когда новость уже
    была отложена предыдущим флашем (см. deferred_count ниже). +10 — заведомо
    больше разницы между любыми двумя значениями importance (максимум 4) —
    поэтому уже отложенная ХОТЬ РАЗ новость гарантированно наберётся раньше
    любой свежей, независимо от её важности. Это классическое решение
    "aging" из планировщиков задач — без него новость с низким importance
    теоретически может застревать в очереди бесконечно, если каждый раз
    находятся более важные свежие новости; с aging после первой же отсрочки
    её приоритет гарантированно обгоняет весь свежий поток, то есть
    максимальная задержка любой новости — ровно один пропущенный флаш."""
    importance = it.get("importance") or 3
    deferred = it.get("deferred_count") or 0
    return importance + 10 * deferred


def build_digest_message(queue_items: list, intro_ru: str | None = None) -> tuple[str | None, list]:
    """Собирает накопленные рутинные новости в ОДИН пост дайджеста.
    queue_items — список dict с ключами source/headline_ru/comment_ru/link/
    topic_tag/comment_digest_ru/importance/deferred_count (см.
    state.append_to_digest_queue; новые поля могут отсутствовать у записей
    из очереди до соответствующего деплоя — см. _digest_line/_digest_priority
    про безопасные дефолты). intro_ru — фраза-интро в фирменном тоне канала
    (см. llm.summarize_digest); если не передана или пустая — используется
    нейтральный заголовок.

    Возвращает (текст_сообщения, leftover) — leftover это те queue_items,
    которые не влезли в лимит Telegram и НЕ вошли в текст (с увеличенным на
    1 deferred_count — см. ниже); вызывающий код (main.py) должен сохранить
    их обратно в очередь, чтобы они ушли со следующим дайджестом, а не
    потерялись. Если queue_items пуст — (None, []).

    03.10.2026 — решение автора, в две итерации:
    (1) раньше при переполнении лимита дайджест резался на несколько
    сообщений подряд "(1/2)", "(2/2)" и т.п. Отказались от этого: второе/
    третье сообщение дайджеста читают заметно реже первого (типичная
    деградация внимания в Telegram-каналах) — "хвост" дайджеста фактически
    проваливался, а не просто приходил чуть позже. Теперь дайджест — всегда
    ОДНО сообщение; то, что не влезло, остаётся в очереди на следующий флаш
    (см. _digest_priority выше, чтобы остаток не терялся и не зависал).
    (2) в тот же день, сразу следующим вопросом автора — какую именно
    новость откладывать при переполнении: сначала просто брали "по порядку"
    (старые новости вперёд — FIFO), но это игнорирует, что среди
    накопившихся новостей не все одинаково важны. Переключились на
    приоритет по _digest_priority (importance + aging) — при переполнении
    откладывается НАИМЕНЕЕ значимая новость, а не просто последняя по
    времени; среди новостей с одинаковым приоритетом порядок остаётся
    стабильным (старые вперёд) — см. сортировку ниже.
    Рассмотренные и отклонённые варианты: (а) резать на несколько
    сообщений, как раньше — отклонено по причине (1) выше; (б) обрезать/
    ронять часть новостей совсем (не переносить) — отклонено: это реальные
    рутинные новости, прошедшие фильтр relevant в llm.py, терять их не
    нужно, задержка на один флаш не критична именно для рутины (громкое и
    так публикуется отдельно и сразу); (в) сортировать по importance БЕЗ
    aging (просто "самое важное вперёд" каждый раз заново) — отклонено:
    доказуемо может уморить голодом новость с низким importance навсегда,
    если каждый следующий флаш приносит что-то более важное — с aging
    максимальная задержка ограничена одним флашем, см. _digest_priority.
    Критерий "количество просмотров" (идея автора) рассмотрен отдельно и
    отклонён для этой задачи — см. сопроводительное сообщение в чате:
    (1) Telegram Bot API в принципе не отдаёт просмотры постов (нужен
    MTProto-клиент с логином через номер телефона, то есть пользовательский
    аккаунт, а не бот-токен — качественно другой, более тяжёлый и рискованный
    тип интеграции); (2) даже если бы было технически просто — просмотры
    появляются только ПОСЛЕ публикации, а эта сортировка нужна ДО неё, для
    ещё неопубликованной новости просмотров ещё не существует."""
    if not queue_items:
        return None, []

    intro = _esc(intro_ru) if intro_ru else "Что вы пропустили"
    header = f"<b>{intro}:</b>\n\n"
    divider = "\n\n"
    budget = TELEGRAM_TEXT_LIMIT - len(header)

    # сортируем по приоритету (выше — раньше), стабильно (Python sort
    # стабилен) — при равном приоритете порядок остаётся исходным
    # (старые новости вперёд, как и раньше), меняется только то, что
    # приоритет теперь не всегда равный.
    ordered = sorted(enumerate(queue_items), key=lambda pair: -_digest_priority(pair[1]))

    included_indices: set = set()
    included_blocks: list = []
    current_len = 0
    for idx, it in ordered:
        comment_text = it.get("comment_digest_ru") or it["comment_ru"]
        block = _digest_line(it["source"], comment_text, it["link"], it.get("topic_tag"))
        add_len = len(block) + (len(divider) if included_blocks else 0)
        if not included_blocks and len(block) > budget:
            # защита от единичной новости, которая сама по себе длиннее
            # лимита (не должно происходить при обычных длинах
            # comment_digest_ru — см. llm.py, правило 4 — но лучше обрезать
            # и отправить дайджест, чем уронить его целиком из-за одной
            # аномально длинной записи)
            block = block[: max(budget - 1, 0)] + "…"
            add_len = len(block)
        elif included_blocks and current_len + add_len > budget:
            continue  # эта новость не влезла — пропускаем, но проверяем следующие по приоритету
        included_indices.add(idx)
        included_blocks.append(block)
        current_len += add_len

    # leftover собирается в исходном порядке очереди (не в порядке
    # включения по приоритету выше) — чтобы следующий вызов снова видел
    # старые новости первыми при прочих равных значениях приоритета, а не в
    # том порядке, в котором они были пропущены в этот раз.
    leftover = []
    for idx, it in enumerate(queue_items):
        if idx in included_indices:
            continue
        it = dict(it)
        it["deferred_count"] = (it.get("deferred_count") or 0) + 1
        if it["deferred_count"] > 1:
            # по конструкции _digest_priority это не должно повторяться
            # (после первой отсрочки приоритет гарантированно выше любой
            # свежей новости) — если всё же произошло, это значит, что
            # уже отложенных новостей в один присест набралось больше, чем
            # влезает в одно сообщение, то есть аномально большая нагрузка,
            # а не обычный "горячий день". Логируем громко, чтобы это не
            # прошло незамеченным.
            logger.error(
                "Новость откладывается ВТОРОЙ раз подряд (source=%s) — "
                "гарантия 'максимум один пропущенный флаш' нарушена из-за "
                "необычно большого числа уже отложенных новостей "
                "одновременно, см. docstring build_digest_message",
                it.get("source"),
            )
        leftover.append(it)

    # итоговое сообщение собрано в порядке included_blocks — то есть по
    # приоритету (важное/отложенное выше), а не в исходном порядке очереди.
    # Это сознательный побочный эффект решения сортировать по важности:
    # самая значимая новость дайджеста теперь оказывается наверху
    # сообщения, а не просто "первая по времени".
    message = header + divider.join(included_blocks)
    return message, leftover


def send_message(
    text: str,
    silent: bool = False,
    disable_preview: bool = False,
    chat_id: str | None = None,
    parse_mode: str | None = "HTML",
) -> bool:
    """silent=True шлёт сообщение без звука/вибрации у подписчиков
    (Telegram disable_notification) — сам пост при этом появляется в канале
    сразу же, ничего не задерживается. Используется ночью (23:00–08:00 МСК,
    см. timeutil.is_night_msk), чтобы не будить подписчиков уведомлением,
    но и не жертвовать своевременностью для тех, кто открывает канал сам.

    disable_preview=True отключает предпросмотр ссылки под сообщением
    (Telegram disable_web_page_preview). Используется для дайджеста (24.09.
    2026): там в ОДНОМ сообщении сразу несколько разных ссылок (по одной на
    каждую новость), а Telegram рендерит превью только для первой найденной
    ссылки в тексте — то есть подписчик видел бы превью только последней
    добавленной в дайджест новости, как будто весь пост про неё одну.
    01.10.2026 это же отключение на два дня распространили и на одиночные
    "громкие" посты (main.py, ветка urgency == "breaking") — но там ссылка
    всего одна, так что исходной причины (неправильный выбор превью среди
    нескольких ссылок) там никогда не было; 03.10.2026, решение автора —
    вернули превью одиночным постам обратно (main.py больше не передаёт
    disable_preview для этой ветки, действует дефолт False) — для дайджеста
    причина осталась в силе, там без изменений.

    26.09.2026, вечер — `chat_id`/`parse_mode` необязательны, по умолчанию
    не меняют поведение (chat_id=None → config.TELEGRAM_CHAT_ID, как и
    раньше; parse_mode="HTML", как и раньше). Нужны scripts/issue_v2.py
    (минимальный запуск v2, решение менеджера): выпуск и разбор ошибок
    фактчекера уходят не в канал, а в личку автору (chat_id=
    config.TELEGRAM_AUTHOR_CHAT_ID), причём разбор ошибок — обычным
    текстом, без HTML (parse_mode=None) — это отчёт для автора, а не пост
    в канал, там нет смысла рисковать HTML-эскейпингом текста, который сам
    же Фактчекер написал в свободной форме (`note` в claims)."""
    url = f"https://api.telegram.org/bot{config.TELEGRAM_BOT_TOKEN}/sendMessage"
    payload = {
        "chat_id": chat_id if chat_id is not None else config.TELEGRAM_CHAT_ID,
        "text": text,
        "disable_web_page_preview": disable_preview,
        "disable_notification": silent,
    }
    if parse_mode is not None:
        payload["parse_mode"] = parse_mode
    try:
        resp = requests.post(url, json=payload, timeout=config.REQUEST_TIMEOUT)
        if resp.status_code != 200:
            logger.error("Telegram API вернул ошибку %s: %s", resp.status_code, resp.text)
            return False
        return True
    except Exception as exc:
        logger.error("Не удалось отправить сообщение в Telegram: %s", exc)
        return False
