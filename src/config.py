# (день, ночь — неважно), рутина копится в очередь (state/digest_queue.json) и
# уходит одним сборным постом на ближайшей из фиксированных точек ниже.
# Причина: часть подписчиков — реальные знакомые, добавленные вручную, и поток
# отдельных постов по каждому мелкому поводу (а не только ночью) их утомляет;
# плюс дайджест читается лучше, чем россыпь мелких сообщений. Времена подобраны
# под рынок США/Европы (МСК): 08:00 — закрывает ночь + азиатскую сессию; 12:00 —
# закрывает утро/предоткрытие Европы; 17:00 — сразу после открытия США (~16:30
# МСК), без 6-часового ожидания; 21:00 — закрывает основной объём сессии США
# перед закрытием (~23:00 МСК), а "хвост" 21:00-08:00 естественно уходит в
# утренний дайджест. Список можно менять при необходимости (например, если
# аудитория станет заметно нероссийской — см. обоснование в чате).
