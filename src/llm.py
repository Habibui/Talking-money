def summarize_digest(queue_items: list) -> str | None:
    """queue_items — список dict с ключом headline_ru (уже переведённые
    заголовки накопленных рутинных новостей). Возвращает короткую фразу-интро
    для дайджеста в фирменном тоне канала, либо None при ошибке (тогда
    main.py использует нейтральный запасной заголовок — сама отправка
    дайджеста от этого не должна зависеть)."""
    if not queue_items:
        return None

    # timeout=30 — без него SDK по умолчанию ждёт до 600 секунд на один
    # запрос (плюс встроенные повторы), а это при 15-минутном интервале
    # между запусками пайплайна означает, что один подвисший вызов может
    # продержать job почти до следующего срабатывания cron — и тогда его
    # оборвёт cancel-in-progress: true (см. .github/workflows/publish.yml),
    # не дав шагу коммита state отработать вовремя. Обнаружено 13.09.2026 —
    # именно так, судя по всему, возник дубль поста про Ормузский пролив.
    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=30.0)
    headlines = "\n".join(f"- {it['headline_ru']}" for it in queue_items)

    try:
        response = client.messages.create(
            model=config.LLM_MODEL,
            max_tokens=100,
            system=DIGEST_INTRO_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": headlines}],
        )
        raw = "".join(
            block.text for block in response.content if getattr(block, "type", "") == "text"
        ).strip()
        return raw.strip('"«» ') or None
    except Exception as exc:
        logger.error("Не удалось получить интро для дайджеста: %s", exc)
        return None


DEDUP_CHECK_SYSTEM_PROMPT = """\
Ты помогаешь антидублирующему фильтру телеграм-канала про экономику и \
бизнес. Тебе дают два коротких русскоязычных текста (заголовок + \
комментарий) — один новый, один уже опубликованный в канале. У них может \
формально совпасть пара слов или цифр, но это не всегда значит, что это \
одна и та же новость — а может значить и то, и другое, поэтому дальше \
решаешь именно ты, не формула.

Ответь "yes", если оба текста — про ОДНО И ТО ЖЕ конкретное событие, \
решение, отчёт или релиз статистики, пусть даже с разных ракурсов, разными \
словами и из разных источников. Типичный случай: три издания написали про \
одно и то же решение центробанка поднять ставку, но один делает акцент на \
реакции инвесторов, другой — на политическом давлении, третий — на \
инфляционных рисках; при этом главный факт (кто, что именно и когда \
сделал) один и тот же.

Ответь "no", если это разные события — пусть даже с похожими фоновыми \
словами или общей темой (например, разные центробанки, разные компании, \
разные периоды статистики, или тексты просто оба упоминают одну и ту же \
макроэкономическую предпосылку типа цены на нефть, но говорят о разных \
конкретных новостях).

Ответь строго одним словом: yes или no — без пояснений, без пунктуации."""


def confirm_same_event(new_text: str, candidate_text: str) -> bool | None:
    """Точечная (дешёвая, узкая) проверка для пограничных случаев из
    src/dedup.py (см. find_ambiguous_match) — когда текстового сходства мало,
    но 2+ значимых токена совпало, и по формуле нельзя понять, это дубль по
    факту или просто совпадение фоновых слов канала (см. инцидент 18.09.2026,
    claude/pipeline-v1-setup.md — доказано, что порогом Jaccard эту пару
    случаев в принципе не разделить). Вызывается НЕ для каждой новости, а
    только когда src/dedup.py уже отметил пару как подозрительную — основной
    объём новостей эту функцию вообще не трогает.

    new_text/candidate_text — уже "headline_ru + comment_ru" одной строкой
    (вызывающий код сам решает, как их склеивать — см. main.py).

    Возвращает True/False, или None при сбое запроса (сеть/формат ответа) —
    в этом случае main.py должен считать, что дубль НЕ подтверждён (не
    блокировать публикацию из-за сбоя вспомогательной проверки; риск
    редкого пропущенного дубля тут менее вреден, чем риск молча потерять
    новость из-за сетевой ошибки в проверке, которая вообще не обязана
    существовать для публикации)."""
    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=15.0)
    user_content = f"Новый текст:\n{new_text}\n\nУже опубликованный текст:\n{candidate_text}"

    try:
        response = client.messages.create(
            model=config.LLM_MODEL,
            max_tokens=5,
            system=DEDUP_CHECK_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_content}],
        )
        raw = "".join(
            block.text for block in response.content if getattr(block, "type", "") == "text"
        ).strip().lower()
        if raw.startswith("yes"):
            return True
        if raw.startswith("no"):
            return False
        logger.warning("Неожиданный ответ точечной проверки дублей: %r", raw)
        return None
    except Exception as exc:
        logger.error("Ошибка точечной LLM-проверки дублей: %s", exc)
        return None


def translate_and_comment(item: dict, recent_posts: list | None = None) -> dict | None:
    """item — {source, title, summary, link}. recent_posts — список недавних
    (обычно за последние ~48ч) уже опубликованных новостей канала, вида
    {source, headline_ru, comment_ru}, для смысловой проверки на дубли/апдейты
    между разными источниками (см. state.load_recent_posts). Возвращает
    {"relevant": bool, "story_status": "new"|"update"|"duplicate",
    "urgency": "breaking"|"routine", "headline_ru": ..., "comment_ru": ...}
    или None при ошибке запроса/парсинга (не путать с relevant=False — это
    валидный ответ, просто новость не подходит по теме и её не нужно
    публиковать)."""

    # timeout=30 — см. комментарий в summarize_digest() выше: без явного
    # таймаута один подвисший вызов Anthropic может держать job почти до
    # следующего запуска и попасть под cancel-in-progress: true уже после
    # успешной отправки другой новости в Telegram, но до коммита state.
    client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY, timeout=30.0)

    recent_block = ""
    if recent_posts:
        recent_block = "\n".join(
            f"- [{p['source']}] {p['headline_ru']} — {p['comment_ru']}" for p in recent_posts
        )

    # Две попытки (item["summary"] — уже полученный текст, повторного похода
    # в сеть здесь нет). Смысл повтора не в том, что не хватило текста, а в
    # том, что модель могла один раз сбиться на кривом JSON/непереводе —
    # частый случай, когда жёсткая обрезка по числу символов разрезает текст
    # прямо посреди цитаты (незакрытая кавычка на входе). Поэтому 1-я попытка
    # режет по MAX_ARTICLE_CHARS (не гонять на каждый обычный запрос лишние
    # токены), а 2-я (только если 1-я сбилась именно на формате) берёт ВЕСЬ
    # уже полученный текст без обрезки вообще — это не "другая длина среза",
    # а гарантированное отсутствие среза как причины: у настоящего конца
    # статьи (или её sanity-предела ARTICLE_FETCH_HARD_CAP_CHARS в sources.py)
    # нет разумных причин обрываться посреди незакрытой кавычки, в отличие от
    # произвольной точки на MAX_ARTICLE_CHARS. См. историю ошибки
    # "Unterminated string" 13-14.09.2026.
    char_limits = [config.MAX_ARTICLE_CHARS, None]  # None — без обрезки, весь текст

    # Investing.com (и изредка другие источники) нередко отдают боту 403 на
    # саму статью, а RSS-лид у той же заметки при этом тоже пуст — в таком
    # случае article_text ниже — буквально пустая строка, и без явной
    # пометки промпт выглядит как "Краткое содержание (en): " с пустым
    # хвостом. Формально это не ломает запрос (заголовок title всё равно
    # передаётся отдельной строкой выше и никогда не пуст), но модель не
    # видит разницы между "лид пуст" и "лид просто короткий" — а это разные
    # ситуации: во втором случае можно уверенно опираться на текст, в первом
    # единственный источник фактов — сам заголовок, и дофантазировать
    # детали (даже правдоподобные) особенно легко. Явно называем эту
    # ситуацию моделью, а не оставляем пустую строку без объяснения —
    # остальные правила (не выдумывать цифры/детали) уже есть в
    # SYSTEM_PROMPT, здесь только даём модели опознать сам случай.
    summary_is_empty = not item["summary"].strip()

    for attempt, char_limit in enumerate(char_limits, start=1):
        is_last_attempt = attempt == len(char_limits)
        article_text = item["summary"] if char_limit is None else item["summary"][:char_limit]

        if summary_is_empty:
            content_field = (
                "[источник не отдал текст статьи, а RSS-лид у этой заметки тоже "
                "пуст — единственный источник фактов здесь заголовок выше; не "
                "добавляй цифры, подробности или детали, которых в заголовке нет]"
            )
        else:
            content_field = article_text

        user_content = (
            f"Источник: {item['source']}\n"
            f"Заголовок (en): {item['title']}\n"
            f"Краткое содержание (en): {content_field}\n"
        )
        if recent_block:
            user_content += (
                f"\nНедавно опубликованные в канале новости (для проверки на "
                f"дубли/апдейты):\n{recent_block}\n"
            )

        try:
            response = client.messages.create(
                model=config.LLM_MODEL,
                max_tokens=500,
                system=SYSTEM_PROMPT,
                messages=[{"role": "user", "content": user_content}],
            )
            raw = "".join(
                block.text for block in response.content if getattr(block, "type", "") == "text"
            ).strip()

            # модель иногда всё равно оборачивает ответ в ```json ... ``` — подчистим
            if raw.startswith("```"):
                raw = raw.strip("`")
                raw = raw.split("\n", 1)[1] if "\n" in raw else raw
                if raw.lower().startswith("json"):
                    raw = raw[4:]

            # берём только первый валидный JSON-объект и игнорируем всё, что
            # модель могла добавить после него (лишний текст/пояснение) —
            # обычный json.loads падает на этом с "Extra data"
            data, _ = json.JSONDecoder().raw_decode(raw)
            if "headline_ru" not in data or "comment_ru" not in data:
                raise ValueError(f"В ответе модели нет нужных ключей: {data}")
            data.setdefault("relevant", True)  # старые/неполные ответы считаем релевантными
            data.setdefault("story_status", "new")
            data.setdefault("urgency", "routine")

            # то, что реально уйдёт в канал (см. main.py), должно быть на русском —
            # если релевантно и не дубль, а headline/comment по факту остались на
            # английском (модель не перевела), не публикуем брак, а считаем это
            # ошибкой перевода
            if data["relevant"] and data["story_status"] != "duplicate":
                headline = data.get("headline_ru", "")
                comment = data.get("comment_ru", "")
                if not _is_mostly_cyrillic(headline) or not _is_mostly_cyrillic(comment):
                    raise ValueError(
                        f"Модель вернула непереведённый текст для {item['source']}: "
                        f"headline_ru={headline!r}, comment_ru={comment!r}"
                    )

            return data

        except (json.JSONDecodeError, ValueError) as exc:
            # именно эти два класса ошибок — про формат ответа модели самой
            # по себе (не распарсился JSON / нет нужных ключей / не перевела),
            # а не про сеть или сам API — поэтому имеет смысл повторить с
            # другой обрезкой текста, а не сразу сдаваться
            if not is_last_attempt:
                limit_desc = f"{char_limit} симв." if char_limit is not None else "без обрезки"
                next_desc = (
                    f"{char_limits[attempt]} симв." if char_limits[attempt] is not None else "весь текст без обрезки"
                )
                logger.warning(
                    "Сбой формата ответа модели для %s (%s) при обрезке (%s), "
                    "повтор (%s): %s",
                    item["source"], item["link"], limit_desc, next_desc, exc,
                )
                continue
            logger.error(
                "Ошибка перевода/комментария для %s (%s) после повтора: %s",
                item["source"], item["link"], exc,
            )
            return None

        except Exception as exc:
            # сетевые/API-ошибки (таймаут, 5xx и т.п.) — повтор с другой
            # длиной текста тут не при чём, а свои повторы на этот случай уже
            # делает сам anthropic SDK; сдаёмся сразу, как и раньше
            logger.error(
                "Ошибка перевода/комментария для %s (%s): %s", item["source"], item["link"], exc
            )
            return None

    return None  # недостижимо (цикл всегда либо return, либо raise на последней попытке)
