# (?<!...) / (?!...) вместо \b — явные границы по конкретным классам символов,
# а не полагание на то, как re трактует \w для кириллицы в данной версии/
# окружении Python; сокращение не должно быть приклеено к букве/цифре ни с
# одной стороны (но дефис/тире/пунктуация вокруг — нормальная граница).
_ABBREVIATION_PATTERNS = {
    abbr: re.compile(
        r"(?<![A-Za-zА-Яа-яЁё0-9])" + re.escape(abbr) + r"(?![A-Za-zА-Яа-яЁё0-9])"
    )
    for abbr in ABBREVIATION_FULL_NAMES
}


def find_known_abbreviations(headline_ru: str, comment_ru: str) -> dict:
    """Ищет в уже переведённом тексте вхождения известных сокращений из
    ABBREVIATION_FULL_NAMES (точное совпадение регистра, с границами не по
    буквам/цифрам). Возвращает {найденное_сокращение: полное_русское_имя} —
    пусто, если ничего не нашлось (обычный случай, основной объём текстов
    сюда вообще не попадает)."""
    text = f"{headline_ru} {comment_ru}"
    return {
        abbr: full
        for abbr, full in ABBREVIATION_FULL_NAMES.items()
        if _ABBREVIATION_PATTERNS[abbr].search(text)
    }


def _is_mostly_cyrillic(text: str, min_ratio: float = 0.5) -> bool:
    """Грубая, но дешёвая защита от случая, когда модель по какой-то причине
    не перевела текст и вернула headline_ru/comment_ru как есть на
    английском (наблюдался живой случай 11.09.2026 — заголовок ушёл в канал
    непереведённым). Считаем долю кириллических букв среди всех букв в
    тексте — у реально переведённого текста она должна быть высокой, даже
    если там мелькают английские названия компаний/тикеры/аббревиатуры."""
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return True  # текста без букв (только цифры/пунктуация) не блокируем
    cyrillic = sum(1 for c in letters if "Ѐ" <= c <= "ӿ")
    return (cyrillic / len(letters)) >= min_ratio

