def _is_mostly_cyrillic(text: str, min_ratio: float = 0.5) -> bool:
    """Грубая, но дешёвая защита от случая, когда модель по какой-то причине
    не перевела текст и вернула headline_ru/comment_ru как есть на
    английском (наблюдался живой случай 11.09.2026 — заголовок ушёл в канал
    непереведённым). Считаем долю кириллических букв среди всех букв в
    тексте — у реально переведённого текста она должна быть высокой, даже
    если там мелькают английские названия компаний/тикеры/аббревиатуры."""
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return True  # текста без букв (только цифры/пунктуация) не блокируем
    cyrillic = sum(1 for c in letters if "Ѐ" <= c <= "ӿ")
    return (cyrillic / len(letters)) >= min_ratio

